// -----------STRINGS-------------------
//con let se declara la variable, luego solo se reemplaza el valor
// sin volver a declararla
let nombre = 'Peter Parker';
console.log(nombre);

nombre = 'Ben Parker';
console.log(nombre);

// -----------BOOLEANS-------------------
let esMarvel = true;
console.log(typeof(esMarvel));


// -----------NUMBERS-------------------
let edad = 33;
console.log(typeof(edad));

edad = 33.001;
console.log(typeof(edad));


// -----------UNDEFINED-------------------
let superHeroeSpiderMan;
console.log(typeof(superHeroeSpiderMan));


// -----------NULL-------------------
let soyNull = null;
console.log(typeof(soyNull));

// -----------SYMBOL-------------------
let symbol1 = Symbol('a');
let symbol2 = Symbol('a');
console.log(typeof(symbol1));

console.log(symbol1 === symbol2);



